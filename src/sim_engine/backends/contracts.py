"""Simulator-independent execution and observation contracts."""
from dataclasses import dataclass
from typing import Any, Protocol

from sim_engine.config import Camera, Physics
from sim_engine.geometry import Pose


@dataclass(frozen=True)
class Capture:
    images: dict[str, Any]
    position: list[float]
    rotation_xyzw: list[float]
    sensors: dict[str, dict]
    calibration: dict


class Environment(Protocol):
    physics: Physics
    scene_loads: int

    def reset(self, episode: dict, camera: Camera, seed: int): ...
    def capture(self) -> Capture: ...
    def observe_views(self, yaw: float) -> dict[str, Capture]: ...
    def enable_depth(self) -> None: ...
    def identity(self) -> dict: ...
    def pose(self) -> Pose: ...
    def position(self) -> list[float]: ...
    def step(self, action): ...
    def velocity_step(self, linear_mps, angular_rps, dt, allow_sliding): ...
    def distance(self, start, end) -> float: ...
    def snap(self, point): ...
    def shortest_path(self, start, end): ...
    def close(self) -> None: ...
